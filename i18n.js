let currentLang = localStorage.getItem("q-lang") === "kk" ? "kk" : "ru";

function t(key, vars) {
  const pack = I18N[currentLang] || I18N.ru;
  let text = pack[key] || I18N.ru[key] || key;
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replaceAll(`{${name}}`, String(value));
    });
  }
  return text;
}

function applyI18n(root) {
  const scope = root || document;
  document.documentElement.lang = currentLang === "kk" ? "kk" : "ru";
  scope.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  scope.querySelectorAll("[data-i18n-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nLabel));
  });
  document.querySelectorAll(".lang-switch button").forEach((button) => {
    button.classList.toggle("is-on", button.dataset.lang === currentLang);
    button.setAttribute("aria-pressed", button.dataset.lang === currentLang ? "true" : "false");
  });
  if (document.title && document.body.dataset.titleKey) document.title = t(document.body.dataset.titleKey);
  window.dispatchEvent(new CustomEvent("q-lang"));
}

function setLang(lang) {
  currentLang = lang === "kk" ? "kk" : "ru";
  localStorage.setItem("q-lang", currentLang);
  applyI18n();
}

document.addEventListener("click", (event) => {
  const button = event.target.closest(".lang-switch [data-lang]");
  if (!button) return;
  event.preventDefault();
  setLang(button.dataset.lang);
});

applyI18n();
